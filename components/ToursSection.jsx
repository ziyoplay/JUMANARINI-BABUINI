export default function ToursSection() {
  const [selectedCategory, setSelectedCategory] = useState('all');
  const [selectedVehicle, setSelectedVehicle] = useState('sedan');
  const [selectedTour, setSelectedTour] = useState(null);

  const filteredTours = selectedCategory === 'all' 
    ? TOURS_DATA 
    : TOURS_DATA.filter(t => t.category === selectedCategory);

  function handleSelectForBooking(tourTitle, vehicleType) {
    const bookingSection = document.getElementById('booking');
    if (bookingSection) {
      bookingSection.scrollIntoView({ behavior: 'smooth' });
    }
    const selectElem = document.getElementById('tour');
    if (selectElem) {
      selectElem.value = tourTitle;
    }
    const vehicleElem = document.getElementById('vehicleType');
    if (vehicleElem && vehicleType) {
      vehicleElem.value = vehicleType;
    }
  }

  return (
    <section className="section" id="tours">
      <div className="section-head">
        <span className="eyebrow">Маршруты и Трансферы</span>
        <h2>Приватные дневные туры и экскурсионные трансферы</h2>
        <p>
          Все поездки индивидуальные «от двери до двери». Фиксированная цена за машину, 
          включает кондиционер, бензин, питьевую воду и опытного водителя.
        </p>
      </div>

      {/* Vehicle Type Switcher Header Bar */}
      <div className="vehicle-selector-bar">
        <span className="v-bar-label">Класс автомобиля:</span>
        <div className="v-pill-group">
          {VEHICLE_TYPES.map(v => (
            <button
              key={v.id}
              type="button"
              className={`v-pill ${selectedVehicle === v.id ? 'active' : ''}`}
              onClick={() => setSelectedVehicle(v.id)}
            >
              <span className="v-name">{v.name}</span>
              <span className="v-badge">{v.badge}</span>
            </button>
          ))}
        </div>
      </div>

      {/* Category Tabs */}
      <div className="tour-categories-tabs">
        {TOUR_CATEGORIES.map(cat => (
          <button
            key={cat.id}
            type="button"
            className={`tour-tab-btn ${selectedCategory === cat.id ? 'active' : ''}`}
            onClick={() => setSelectedCategory(cat.id)}
          >
            {cat.label}
            {cat.id !== 'all' && (
              <span className="tab-count">
                {TOURS_DATA.filter(t => t.category === cat.id).length}
              </span>
            )}
          </button>
        ))}
      </div>

      {/* Tours Grid */}
      <div className="grid">
        {filteredTours.map((tour) => {
          const currentPrice = tour.prices ? tour.prices[selectedVehicle] : 50;
          const currentVehicleInfo = VEHICLE_TYPES.find(v => v.id === selectedVehicle);

          return (
            <div className="card tour-card-enhanced" key={tour.id} id={tour.id === 'transfer-khiva-bukhara-three-fortresses' ? 'transfers' : undefined}>
              <div className="card-top-badges">
                <span className="badge">{tour.badge}</span>
                {tour.distance && <span className="dist-badge">{tour.distance}</span>}
              </div>

              <img className="tour-photo" src={tour.photo} alt={tour.alt} loading="lazy" />
              
              <div className="card-travel-bar">
                <span className="travel-time-tag"><b>В дороге:</b> {tour.driveTime}</span>
              </div>

              <h3>{tour.title}</h3>
              <div className="route">{tour.route}</div>
              <p>{tour.description}</p>

              {/* Price Matrix Preview */}
              <div className="card-price-row">
                <div className="price-label-wrap">
                  <span className="price-sub">Цена за авто ({currentVehicleInfo?.name}):</span>
                  <div className="price-val">
                    <span className="currency">$</span>
                    <span className="amount">{currentPrice}</span>
                    <span className="per-car">/ авто</span>
                  </div>
                </div>
                <div className="price-vehicle-tag">
                  {currentVehicleInfo?.badge}
                </div>
              </div>
              
              <div className="card-actions">
                <button 
                  type="button" 
                  className="btn-info-link"
                  onClick={() => setSelectedTour(tour)}
                >
                  Детали и маршрут →
                </button>
                <a 
                  className="more" 
                  href="#booking"
                  onClick={() => handleSelectForBooking(tour.title, selectedVehicle)}
                >
                  Забронировать
                </a>
              </div>
            </div>
          );
        })}
      </div>

      {selectedTour && (
        <TourModal 
          tour={selectedTour} 
          initialVehicle={selectedVehicle}
          onClose={() => setSelectedTour(null)} 
          onSelectTourForBooking={handleSelectForBooking}
        />
      )}
    </section>
  );
}
